SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS distrito;
DROP TABLE IF EXISTS provincia;
DROP TABLE IF EXISTS departamento;
SET FOREIGN_KEY_CHECKS = 1;

-- =====================================================================
-- SCHEMA
-- =====================================================================

CREATE TABLE departamento (
  id      INT PRIMARY KEY AUTO_INCREMENT,
  nombre  VARCHAR(100) NOT NULL,
  codigo  VARCHAR(2)   NOT NULL,
  UNIQUE KEY uk_departamento_codigo (codigo),
  INDEX        idx_departamento_codigo (codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE provincia (
  id              INT PRIMARY KEY AUTO_INCREMENT,
  id_departamento INT NOT NULL,
  nombre          VARCHAR(100) NOT NULL,
  codigo          VARCHAR(4)   NOT NULL,
  UNIQUE KEY uk_provincia_codigo (codigo),
  INDEX idx_provincia_departamento (id_departamento),
  INDEX idx_provincia_codigo (codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE distrito (
  id              INT PRIMARY KEY AUTO_INCREMENT,
  id_provincia    INT NOT NULL,
  id_departamento INT NOT NULL,
  nombre          VARCHAR(100) NOT NULL,
  codigo          VARCHAR(6)   NOT NULL,
  UNIQUE KEY uk_distrito_codigo (codigo),
  INDEX idx_distrito_provincia    (id_provincia),
  INDEX idx_distrito_departamento (id_departamento),
  INDEX idx_distrito_codigo       (codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

